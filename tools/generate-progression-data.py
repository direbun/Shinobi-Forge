import json
from pathlib import Path

import openpyxl


ROOT = Path(__file__).resolve().parents[1]
WORKBOOK = ROOT / "source-character-sheet.xlsx"
OUTPUT = ROOT / "server" / "generated-progression-data.mjs"

POOLS = {
    "genjutsuConversions": (939, 943),
    "genjutsuInceptions": (1005, 1010),
    "genjutsuMirages": (1012, 1089),
    "intelligencePlans": (1349, 1369),
    "medicalDoctrines": (1385, 1388),
    "ninjutsuMoldings": (1551, 1567),
    "scoutAdept": (1582, 1589),
    "scoutJack": (1594, 1598),
    "scoutSignatureEffects": (1600, 1602),
    "scoutSignatureTechniques": (1604, 1606),
    "taijutsuMartialTechniques": (1876, 1895),
    "puppetTactics": (2034, 2038),
    "puppetChassis": (2050, 2053),
    "scienceBeastUpgrades": (2460, 2482),
    "scienceTools": (2773, 2812),
    "jujutsuTechniques": (3477, 3488),
    "jujutsuBindingVows": (3491, 3517),
    "lunarWeaponTricks": (3628, 3639),
    "lunarRifleTricks": (3641, 3648),
    "lunarRunes": (3649, 3669),
}

FEATURES = {
    "Genjutsu-Specialist": {11: 945, 13: 946, 20: 947},
    "Intelligence-Operative": {11: 1257, 14: 1258, 20: 1259},
    "Medical-Nin": {20: 1395},
    "Ninjutsu-Specialist": {20: 1460},
    "Taijutsu-Specialist": {11: 1806, 13: 1807, 15: 1808, 18: 1809},
    "Weapon-Specialist": {11: 1917, 14: 1918},
    "Puppet-Master": {15: 2032},
    "Cooking-Nin": {20: 2358},
    "Science-Nin": {11: 2446, 18: 2447},
    "Jujutsu-Sorcerer": {14: 3367},
    "Lunar-Slayer": {13: 3545},
}


def compact(value):
    return " ".join(str(value or "").replace("&emsp;", " ").split())


workbook = openpyxl.load_workbook(WORKBOOK, read_only=True, data_only=True)
sheet = workbook["Feature Lookup"]
needed = {row for bounds in POOLS.values() for row in range(bounds[0], bounds[1] + 1)}
needed.update(row for levels in FEATURES.values() for row in levels.values())
rows = {}
for row_number, row in enumerate(sheet.iter_rows(min_col=1, max_col=4), start=1):
    if row_number in needed:
        rows[row_number] = {
            "name": compact(row[0].value),
            "description": compact(row[3].value),
            "sourceRow": row_number,
        }

pools = {
    name: [rows[row] for row in range(start, end + 1) if rows.get(row, {}).get("name")]
    for name, (start, end) in POOLS.items()
}
features = {
    class_name: {
        str(level): {**rows[row], "type": "Class", "action": "None", "cost": "None"}
        for level, row in levels.items()
        if row in rows
    }
    for class_name, levels in FEATURES.items()
}

source = "// Generated from source-character-sheet.xlsx by tools/generate-progression-data.py.\n"
source += "// Do not edit this file by hand; update the row map and regenerate it.\n\n"
source += "export const GENERATED_OPTION_POOLS = " + json.dumps(pools, ensure_ascii=False, indent=2) + ";\n\n"
source += "export const GENERATED_CLASS_FEATURES = " + json.dumps(features, ensure_ascii=False, indent=2) + ";\n"
OUTPUT.write_text(source, encoding="utf-8")
print(f"Wrote {OUTPUT} with {sum(map(len, pools.values()))} choices and {sum(map(len, features.values()))} feature patches.")
